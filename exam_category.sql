WITH distinct_categories AS (
SELECT DISTINCT exam_category
FROM biogen_consolidated.examination   
),

cleaned AS (
SELECT
exam_category,
TRIM(
REGEXP_REPLACE(
REGEXP_REPLACE(TRIM(exam_category), '^~\\s*', ''),
[\\s:;\\-]+$', ''
)
) AS exam_category_clean
FROM distinct_categories
)

SELECT
exam_category,
CASE
-- hardcoded exact-match overrides (hyphen-suffix pattern; zz-prefix strip)
WHEN exam_category = 'botox - F/U headache' THEN 'Botox- F/U headache'
WHEN exam_category = 'Neurology Exam - full' THEN 'Neurological Examination- Full'
WHEN exam_category = 'Examination - Complete' THEN 'General Examination- Complete'
WHEN exam_category = 'zzExpanded Disability Status Scale (EDSS) in Multiple Sclerosis'
THEN 'Expanded Disability Status Scale (EDSS) in Multiple Sclerosis'

-- special-case uppercase abbreviation
WHEN LOWER(exam_category_clean) = 'er' THEN 'ER'

-- item 4
WHEN LOWER(exam_category_clean) IN ('cardiovascular', 'cardiovascular - (performed)')
THEN 'Cardiovascular'
-- item 5
WHEN LOWER(exam_category_clean) IN ('exam', 'examination', 'general', 'general exam')
THEN 'General Examination'
-- item 6a: Mini-Mental State Exam (MMSE) -- specific standardized instrument
WHEN LOWER(exam_category_clean) IN ('mini mental status exam', 'mmse examination')
THEN 'MMSE Examination'
-- item 6b: Mental Status Exam (MSE) -- distinct, broader clinical assessment
WHEN LOWER(exam_category_clean) IN ('mental status', 'mental status exam', 'mental status examination')
THEN 'MSE Examination'
-- item 7
WHEN LOWER(exam_category_clean) IN ('montreal cognitive assessment', 'moca examination')
THEN 'MOCA Examination'
-- item 8
WHEN LOWER(exam_category_clean) IN ('motor', 'motor examination')
THEN 'Motor Examination'
-- item 9
WHEN LOWER(exam_category_clean) IN ('musculoskeletal - (performed)', 'musculoskeletal examination')
THEN 'Musculoskeletal Examination'
-- item 10
WHEN LOWER(exam_category_clean) IN (
neurologic', 'neurologic examination', 'neurological',
neurological - (performed)', 'neurological exam',
neurological examination', 'neurology exam'
)
THEN 'Neurological Examination'
-- item 12
WHEN LOWER(exam_category_clean) IN ('physical and neurological', 'physical and neurological examination')
THEN 'Physical and Neurological Examination'
-- item 13
WHEN LOWER(exam_category_clean) IN ('physical exam', 'physical examination')
THEN 'Physical Examination'
-- item 14
WHEN LOWER(exam_category_clean) IN ('wrist / hand', 'wrist or hand')
THEN 'Wrist or Hand'
-- additional " / " -> " or " body-region normalizations
WHEN LOWER(exam_category_clean) IN ('hip / thigh', 'hip or thigh')
THEN 'Hip or thigh'
WHEN LOWER(exam_category_clean) IN ('knee / shin', 'knee or shin')
THEN 'Knee or Shin'
WHEN LOWER(exam_category_clean) IN ('shoulder / upper arm', 'shoulder or upper arm')
THEN 'Shoulder or Upper arm'
WHEN LOWER(exam_category_clean) = 'ankle / foot' THEN 'Ankle or Foot'
WHEN LOWER(exam_category_clean) = 'cervical spine/neck' THEN 'Cervical Spine or Neck'
WHEN LOWER(exam_category_clean) = 'elbow/arm' THEN 'Elbow or Arm'
WHEN LOWER(exam_category_clean) = 'hand / upper extremities' THEN 'Hand or upper extremities'
WHEN LOWER(exam_category_clean) = 'hip/pelvis' THEN 'Hips or Pelvis'
WHEN LOWER(exam_category_clean) = 'lumbar spine/lower back' THEN 'Lumbar Spine or Lower Back'
WHEN LOWER(exam_category_clean) = 'neck/upper limb' THEN 'Neck or Upper Limb'
WHEN LOWER(exam_category_clean) = 'thoracic spine/upper back' THEN 'Thoracic Spine or Upper Back'

-- fallback: capitalize only the first character, leave the rest untouched
WHEN exam_category_clean = '' THEN exam_category_clean
ELSE CONCAT(UPPER(LEFT(exam_category_clean, 1)), SUBSTRING(exam_category_clean, 2))
END AS exam_category_std
FROM cleaned
ORDER BY exam_category;














































































































































































































































































































































































































































































































































































































































































































































































































































































































































