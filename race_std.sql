
WITH cleaned AS (
SELECT
a.pat_race,
TRIM(BOTH ',' FROM
REGEXP_REPLACE(
REGEXP_REPLACE(
a.pat_race,
(?i)declined to specify|patient declined|unreported/refused to report|refused to report',
'
),
,{2,}', ','
)
) AS pat_race_cleaned
FROM biogen_consolidated.patient_demographics a
),

normalized AS (
SELECT
pat_race,
pat_race_cleaned,
REGEXP_REPLACE(pat_race_cleaned, '(?i)alaskan native', 'Alaska Native') AS pat_race_norm
FROM cleaned
)

SELECT DISTINCT
n.pat_race,

CASE
WHEN LOWER(TRIM(n.pat_race)) = 'white earth' THEN 'American Indian or Alaska Native'
WHEN LOWER(TRIM(n.pat_race)) = 'other' THEN 'Other Race'
WHEN b_full.Code IS NOT NULL THEN b_full.race
WHEN b_part.Code IS NOT NULL THEN b_part.race
WHEN n.pat_race IS NULL OR TRIM(n.pat_race) = '' THEN 'Unknown'
WHEN LOWER(TRIM(n.pat_race)) = 'unknown' THEN 'Unknown'
WHEN n.pat_race_cleaned = '' THEN 'Declined to specify'
ELSE 'NS'
END AS pat_race_std

FROM normalized n
LEFT JOIN semantics.race b_full
ON LOWER(TRIM(n.pat_race_norm)) = LOWER(TRIM(b_full.race))
LEFT JOIN semantics.race b_part
ON LOWER(TRIM(SUBSTRING_INDEX(n.pat_race_norm, ',', 1))) = LOWER(TRIM(b_part.race))
AND n.pat_race_cleaned <> ''
ORDER BY n.pat_race;


























































































































































































































































































































































































































































































































































































































































































































































































































































































































































































