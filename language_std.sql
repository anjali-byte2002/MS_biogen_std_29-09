
WITH normalized AS (
SELECT
d.pat_lan,
TRIM(d.pat_lan) AS pat_lan_trim,
LOWER(TRIM(d.pat_lan)) AS pat_lan_lower
FROM biogen_consolidated.patient_demographics d
)

SELECT DISTINCT
pat_lan,
CASE
-- blank / null
WHEN pat_lan IS NULL OR pat_lan_trim = '' THEN 'Unknown'
-- unknown / undetermined variants
WHEN pat_lan_lower IN ('unknown','undetermined','undefined') THEN 'Unknown'
-- declined variants
WHEN pat_lan_lower IN ('patient declined','declined to specify') THEN 'Declined to specify'
-- generic catch-all
WHEN pat_lan_lower = 'other' THEN 'Other'
-- special composite mapping
WHEN pat_lan_lower = 'indian (includes hindi & tamil)' THEN 'Hindi and Tamil'
-- verified valid languages (ISO 639-2), normalized spelling/casing
WHEN pat_lan_lower = 'english' THEN 'English'
WHEN pat_lan_lower = 'arabic' THEN 'Arabic'
WHEN pat_lan_lower IN ('spanish;castilian','spanish; castilian') THEN 'Spanish, Castilian'
WHEN pat_lan_lower = 'spanish' THEN 'Spanish'
WHEN pat_lan_lower = 'chinese' THEN 'Chinese'
WHEN pat_lan_lower = 'hindi' THEN 'Hindi'
WHEN pat_lan_lower = 'sign languages' THEN 'Sign languages'
WHEN pat_lan_lower = 'korean' THEN 'Korean'
WHEN pat_lan_lower = 'urdu' THEN 'Urdu'
WHEN pat_lan_lower = 'french' THEN 'French'
WHEN pat_lan_lower = 'russian' THEN 'Russian'
WHEN pat_lan_lower = 'vietnamese' THEN 'Vietnamese'
WHEN pat_lan_lower = 'portuguese' THEN 'Portuguese'
WHEN pat_lan_lower = 'polish' THEN 'Polish'
WHEN pat_lan_lower = 'ukrainian' THEN 'Ukrainian'
WHEN pat_lan_lower = 'hopi' THEN 'Hopi'
WHEN pat_lan_lower = 'italian' THEN 'Italian'
WHEN pat_lan_lower = 'persian' THEN 'Persian'
WHEN pat_lan_lower = 'tamil' THEN 'Tamil'
WHEN pat_lan_lower = 'afar' THEN 'Afar'
WHEN pat_lan_lower IN ('creoles and pidgins,english based','creoles and pidgins, english based') THEN 'Creoles and pidgins, English based'
WHEN pat_lan_lower = 'english, middle (1100-1500)' THEN 'English, Middle (1100-1500)'
WHEN pat_lan_lower IN ('adyghe;adygei','adyghe; adygei') THEN 'Adyghe, Adygei'
WHEN pat_lan_lower = 'abkhazian' THEN 'Abkhazian'
WHEN pat_lan_lower = 'thai' THEN 'Thai'
ELSE 'NS'
END AS pat_lan_std
FROM normalized
ORDER BY pat_lan;



















































































































































































































































































































































































































































































































































































































































































































































































































































































































































































